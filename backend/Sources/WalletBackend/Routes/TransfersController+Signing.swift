import Crypto
import SQLKit
import Vapor

/// Transaction signing (SPEC section 6, ADR-008): a single-use nonce per transfer, and the
/// checks every confirm must pass before any money moves.
extension TransfersController {
    /// `POST /v1/transfers/{id}/challenge`. The app asks for it when the user taps Send,
    /// before the transfer is created: the payload's fields are all known by then, and Face
    /// ID is asked for while the user is looking at the screen. Each call issues a new nonce.
    @Sendable func challenge(_ request: Request) async throws -> Response {
        let user = try request.auth.require(AuthenticatedUser.self)
        guard let uuid = UUID(uuidString: try request.parameters.require("transferID")) else {
            throw APIFailure.invalid("id must be a UUID generated by the client.")
        }
        let transferID = uuid.uuidString.lowercased()
        let sql = try request.sql
        guard let deviceID = user.deviceId,
            let device = try await Self.signingDevice(deviceID, userID: user.id, sql: sql), isTrusted(device)
        else {
            throw APIFailure.deviceNotBound
        }
        try await limitChallenges(transferID: transferID, deviceID: deviceID, sql: sql)
        // Another user's transfer ID is "not found", as everywhere else.
        if let existing = try await sql.select().column("userId").from("transfers")
            .where("id", .equal, transferID)
            .first(decoding: OwnerRow.self), existing.userId != user.id
        {
            throw APIFailure.notFound
        }
        let challenge = ChallengeRow(
            nonce: Tokens.generate(),
            userId: user.id,
            deviceId: deviceID,
            transferId: transferID,
            expiresAt: clock.nowMillis + Self.challengeLifetimeMillis
        )
        try await sql.insert(into: "challenges").model(challenge).run()
        return try await ChallengeDTO(nonce: challenge.nonce, expiresAt: Date(millis: challenge.expiresAt))
            .encodeResponse(status: .created, for: request)
    }

    /// Everything a confirm must prove, checked inside the confirm's transaction:
    ///
    /// 1. The session's device has a signing key, and the signature over the payload bytes
    ///    verifies with it.
    /// 2. The payload is for this transfer: ID, amount, currency, recipient and quote all
    ///    match what is stored. A tampered amount fails here.
    /// 3. The nonce was issued for this transfer to this device, is unused and unexpired, and
    ///    is used up now. A replayed confirm fails here.
    /// 4. On an attested device, the App Attest assertion over the payload verifies and its
    ///    counter went up.
    ///
    /// Throws without changing anything: the transfer stays unconfirmed.
    func verifyApproval(
        _ body: ConfirmRequest?,
        for row: TransferRow,
        user: AuthenticatedUser,
        now: Int64,
        sql: any SQLDatabase
    ) async throws {
        guard let body,
            let payloadData = Data(base64Encoded: body.payload),
            let signatureData = Data(base64Encoded: body.signature)
        else {
            throw APIFailure.signatureRequired
        }
        guard let deviceID = user.deviceId,
            let device = try await Self.signingDevice(deviceID, userID: user.id, sql: sql),
            let keyData = device.signingKey,
            let key = try? P256.Signing.PublicKey(x963Representation: keyData)
        else {
            throw APIFailure.deviceNotBound
        }
        guard let signature = try? P256.Signing.ECDSASignature(derRepresentation: signatureData),
            key.isValidSignature(signature, for: payloadData)
        else {
            throw APIFailure.invalidSignature
        }
        guard let payload = try? JSONDecoder().decode(ConfirmPayload.self, from: payloadData),
            payload.transferId.lowercased() == row.id,
            payload.amountMinor == row.sourceMinor,
            payload.currency == row.sourceCurrency,
            payload.recipientId == row.recipientId,
            payload.quoteId == row.quoteId
        else {
            throw APIFailure.payloadMismatch
        }
        try await useNonce(payload.nonce, for: row, deviceID: deviceID, now: now, sql: sql)
        try await checkAssertion(body.assertion, payload: payloadData, device: device, sql: sql)
    }

    /// A nonce lasts 60 s: long enough to create and confirm, too short to keep a signed
    /// approval around for later.
    static let challengeLifetimeMillis: Int64 = 60_000

    /// Marks the nonce used, in the same statement that checks it, so two confirms can't
    /// both use it. On failure, works out which rule it broke.
    /// `row` is already known to be this user's transfer.
    private func useNonce(_ nonce: String, for row: TransferRow, deviceID: String, now: Int64, sql: any SQLDatabase)
        async throws
    {
        let used = try await sql.update("challenges")
            .set("usedAt", to: now)
            .where("nonce", .equal, nonce)
            .where("userId", .equal, row.userId)
            .where("deviceId", .equal, deviceID)
            .where("transferId", .equal, row.id)
            .where("usedAt", .is, SQLLiteral.null)
            .where("expiresAt", .greaterThanOrEqual, now)
            .returning("nonce")
            .first()
        guard used == nil else {
            return
        }
        guard
            let challenge = try await sql.select().column("*").from("challenges")
                .where("nonce", .equal, nonce)
                .where("userId", .equal, row.userId)
                .where("deviceId", .equal, deviceID)
                .where("transferId", .equal, row.id)
                .first(decoding: ChallengeRow.self)
        else {
            throw APIFailure.invalidNonce
        }
        throw challenge.usedAt != nil ? APIFailure.nonceUsed : APIFailure.nonceExpired
    }

    /// In apple mode every device must be attested: one bound earlier under
    /// `ATTEST_MODE=sandbox` has no App Attest key and is refused, not waved through.
    func isTrusted(_ device: DeviceRow) -> Bool {
        guard case .apple = attestation else {
            return true
        }
        return device.attestPublicKey != nil
    }

    /// Unused, unexpired challenges per transfer and device are capped, and expired ones are
    /// pruned, so a stolen token can't grow the table without limit.
    private func limitChallenges(transferID: String, deviceID: String, sql: any SQLDatabase) async throws {
        let now = clock.nowMillis
        try await sql.delete(from: "challenges").where("expiresAt", .lessThan, now).run()
        let live = try await sql.select().column("nonce").from("challenges")
            .where("transferId", .equal, transferID)
            .where("deviceId", .equal, deviceID)
            .where("usedAt", .is, SQLLiteral.null)
            .all()
        guard live.count < Self.maxLiveChallenges else {
            throw APIFailure.tooManyChallenges
        }
    }

    static let maxLiveChallenges = 5

    private func checkAssertion(_ assertion: String?, payload: Data, device: DeviceRow, sql: any SQLDatabase)
        async throws
    {
        guard case .apple(let verifier) = attestation else {
            return
        }
        guard let attestKey = device.attestPublicKey else {
            throw APIFailure.assertionInvalid
        }
        guard let assertion, let object = Data(base64Encoded: assertion),
            let counter = try? verifier.verifyAssertion(
                object,
                clientData: payload,
                publicKey: attestKey,
                previousCounter: UInt32(clamping: device.signCount)
            )
        else {
            throw APIFailure.assertionInvalid
        }
        // Conditional on the counter read above: of two concurrent assertions, one wins.
        let updated = try await sql.update("devices")
            .set("signCount", to: Int64(counter))
            .where("id", .equal, device.id)
            .where("signCount", .equal, device.signCount)
            .returning("id")
            .first()
        guard updated != nil else {
            throw APIFailure.assertionInvalid
        }
    }

    /// The device, if it belongs to the user and has a signing key.
    private static func signingDevice(_ id: String, userID: String, sql: any SQLDatabase) async throws -> DeviceRow? {
        let device = try await sql.select().column("*").from("devices")
            .where("id", .equal, id).where("userId", .equal, userID)
            .first(decoding: DeviceRow.self)
        return device?.signingKey == nil ? nil : device
    }
}

private struct OwnerRow: Decodable {
    let userId: String
}
