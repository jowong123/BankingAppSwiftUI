import SQLKit
import Vapor

struct QuotesController: Sendable {
    static let lifetimeMillis: Int64 = 30_000
    /// 10 billion minor units: far above any sandbox balance, far below Int64 overflow.
    static let maxSourceMinor: Int64 = 10_000_000_000

    let clock: BackendClock
    let rates: RateTable

    /// Fee in the source currency, deducted before conversion (SPEC section 5):
    /// `target = round((source - fee) * rate)`. Valid for 30 seconds.
    @Sendable func create(_ request: Request) async throws -> Response {
        let user = try request.auth.require(AuthenticatedUser.self)
        let body = try request.content.decode(QuoteRequest.self)
        let source = body.sourceAmount
        guard Currencies.isSupported(source.currency), Currencies.isSupported(body.targetCurrency) else {
            throw APIFailure.invalid("Currency is not supported.")
        }
        guard source.currency != body.targetCurrency else {
            throw APIFailure.invalid("Source and target currency must differ.")
        }
        guard source.amountMinor > 0, source.amountMinor <= Self.maxSourceMinor else {
            throw APIFailure.invalid("Amount is out of range.")
        }
        let fee = MoneyMath.fee(sourceMinor: source.amountMinor, currency: source.currency)
        guard source.amountMinor > fee else {
            throw APIFailure.invalid("Amount must be more than the fee.")
        }
        guard let rate = rates.rate(from: source.currency, to: body.targetCurrency),
            let target = MoneyMath.convert(
                netSourceMinor: source.amountMinor - fee,
                sourceCurrency: source.currency,
                targetCurrency: body.targetCurrency,
                rate: rate
            ),
            target > 0
        else {
            throw APIFailure.invalid("Amount is too small to convert.")
        }

        let row = QuoteRow(
            id: "q_\(UUID().uuidString.lowercased())",
            userId: user.id,
            sourceMinor: source.amountMinor,
            sourceCurrency: source.currency,
            targetMinor: target,
            targetCurrency: body.targetCurrency,
            feeMinor: fee,
            rate: rate.description,
            expiresAt: clock.nowMillis + Self.lifetimeMillis
        )
        try await request.sql.insert(into: "quotes").model(row).run()
        return try await QuoteDTO(row).encodeResponse(status: .created, for: request)
    }
}

/// Creating a transfer only records it as `awaiting_confirmation`. The signed confirm that
/// moves money arrives in Phase 7 (SPEC section 6), so no balance changes here.
struct TransfersController: Sendable {
    let clock: BackendClock

    @Sendable func create(_ request: Request) async throws -> Response {
        let user = try request.auth.require(AuthenticatedUser.self)
        let body = try request.content.decode(TransferRequest.self)
        guard let uuid = UUID(uuidString: body.id) else {
            throw APIFailure.invalid("id must be a UUID generated by the client.")
        }
        let transferID = uuid.uuidString.lowercased()
        // The key must be the transfer's own ID (SPEC section 5): a client that made a
        // fresh key per attempt would never get a replay.
        guard request.headers.first(name: IdempotencyMiddleware.header)?.lowercased() == transferID else {
            throw APIFailure(
                status: .unprocessableEntity,
                code: APIFailure.idempotencyMismatch.code,
                message: "Idempotency-Key must be the transfer id."
            )
        }
        let now = clock.nowMillis

        // Idempotent on the transfer ID itself, not only through the middleware's record
        // (which expires after 24 h and is released on a 5xx). A retry of a transfer that
        // was committed always gets the transfer back, never "quote expired".
        if let existing = try await existingTransfer(transferID, matching: body, userID: user.id, sql: request.sql) {
            return try await TransferDTO(existing).encodeResponse(status: .ok, for: request)
        }

        let row = try await request.db.transaction { database in
            let sql = try database.sqlDatabase()
            let checked = try await validate(body, transferID: transferID, userID: user.id, now: now, sql: sql)
            let row = TransferRow(
                id: transferID,
                userId: user.id,
                quoteId: checked.quote.id,
                recipientId: checked.recipient.id,
                sourceAccountId: checked.account.id,
                sourceMinor: checked.quote.sourceMinor,
                sourceCurrency: checked.quote.sourceCurrency,
                targetMinor: checked.quote.targetMinor,
                targetCurrency: checked.quote.targetCurrency,
                feeMinor: checked.quote.feeMinor,
                status: "awaiting_confirmation",
                failureReason: nil,
                createdAt: now,
                updatedAt: now
            )
            try await sql.insert(into: "transfers").model(row).run()
            return row
        }
        return try await TransferDTO(row).encodeResponse(status: .created, for: request)
    }

    private struct Checked {
        let quote: QuoteRow
        let recipient: RecipientRow
        let account: AccountRow
    }

    /// Everything must belong to the user (404 otherwise, so other users' IDs aren't
    /// confirmed to exist), the quote must be live and unused, the currencies must line
    /// up, and the account must cover the source amount.
    private func validate(
        _ body: TransferRequest,
        transferID: String,
        userID: String,
        now: Int64,
        sql: any SQLDatabase
    ) async throws -> Checked {
        guard
            let quote = try await sql.select().column("*").from("quotes")
                .where("id", .equal, body.quoteId).where("userId", .equal, userID)
                .first(decoding: QuoteRow.self)
        else { throw APIFailure.notFound }
        // The instant of expiry counts as expired, matching the app's `FXQuote.isExpired`.
        guard now < quote.expiresAt else { throw APIFailure.quoteExpired }

        guard
            let recipient = try await sql.select().column("*").from("recipients")
                .where("id", .equal, body.recipientId).where("userId", .equal, userID)
                .first(decoding: RecipientRow.self)
        else { throw APIFailure.notFound }
        guard recipient.currency == quote.targetCurrency else {
            throw APIFailure.invalid("Recipient currency doesn't match the quote.")
        }

        guard
            let account = try await sql.select().column("*").from("accounts")
                .where("id", .equal, body.sourceAccountId).where("userId", .equal, userID)
                .first(decoding: AccountRow.self)
        else { throw APIFailure.notFound }
        guard account.currency == quote.sourceCurrency else {
            throw APIFailure.invalid("Account currency doesn't match the quote.")
        }
        guard account.balanceMinor >= quote.sourceMinor else { throw APIFailure.insufficientFunds }

        let quoteUsed = try await sql.select().column("id").from("transfers")
            .where("quoteId", .equal, quote.id).first()
        guard quoteUsed == nil else { throw APIFailure.quoteUsed }

        return Checked(quote: quote, recipient: recipient, account: account)
    }

    /// The transfer with this ID if it exists for this user with the same details. The same
    /// ID with different details, or another user's ID, is a 409.
    private func existingTransfer(
        _ id: String,
        matching body: TransferRequest,
        userID: String,
        sql: any SQLDatabase
    ) async throws -> TransferRow? {
        guard
            let row = try await sql.select().column("*").from("transfers")
                .where("id", .equal, id)
                .first(decoding: TransferRow.self)
        else { return nil }
        // Another user's transfer is "not found", as on every other route, so the reply never
        // confirms that someone else's ID exists.
        guard row.userId == userID else { throw APIFailure.notFound }
        guard row.quoteId == body.quoteId, row.recipientId == body.recipientId,
            row.sourceAccountId == body.sourceAccountId
        else {
            throw APIFailure(status: .conflict, code: "transfer_exists", message: "A different transfer has this id.")
        }
        return row
    }

    @Sendable func show(_ request: Request) async throws -> TransferDTO {
        let user = try request.auth.require(AuthenticatedUser.self)
        let id = try request.parameters.require("transferID")
        guard
            let row = try await request.sql.select().column("*").from("transfers")
                .where("id", .equal, id.lowercased()).where("userId", .equal, user.id)
                .first(decoding: TransferRow.self)
        else { throw APIFailure.notFound }
        return TransferDTO(row)
    }
}
